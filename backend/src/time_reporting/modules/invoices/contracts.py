"""Public contract of the invoices module.

Other modules may import only this file: DTOs, commands, queries and domain exceptions. Handlers
for these messages are registered in ``invoices.module``; ORM entities never leave the module.
"""

from dataclasses import dataclass
from datetime import date, datetime
from decimal import Decimal
from enum import StrEnum
from typing import Literal, get_args
from uuid import UUID

from time_reporting.core.cqrs import Command, Query
from time_reporting.modules.timesheets.contracts import BillingPeriodRef

type ClearableInvoiceField = Literal["vat_rate", "vat_note", "your_reference", "notes"]

# Optional fields that ``UpdateInvoiceDraft.clear_fields`` can reset to ``None``.
CLEARABLE_INVOICE_FIELDS: tuple[ClearableInvoiceField, ...] = get_args(
    ClearableInvoiceField.__value__
)


class InvoiceStatus(StrEnum):
    """An invoice's place in its lifecycle. ``DRAFT`` is mutable (header and lines); every other
    status is set only by the future ``invoices`` issue/paid/void commands (T8) and, once
    ``ISSUED``, the invoice itself becomes immutable — only ``paid_on``/``voided_at`` change from
    there."""

    DRAFT = "draft"
    ISSUED = "issued"
    PAID = "paid"
    VOID = "void"


class InvoiceLineKind(StrEnum):
    """Where a line came from. ``TIME`` and ``EXPENSE`` lines are generated by
    ``CreateInvoiceDraft`` from a billing period's export rows (see
    ``timesheets.contracts.GetBillingPeriodExportRows``); ``MANUAL`` lines are added free-form
    while the invoice is a draft."""

    TIME = "time"
    EXPENSE = "expense"
    MANUAL = "manual"


# --- DTOs ---


@dataclass(frozen=True, slots=True, kw_only=True)
class InvoiceCustomerDTO:
    """The subset of a draft's customer needed to display it alongside the invoice."""

    id: UUID
    name: str
    currency: str


@dataclass(frozen=True, slots=True, kw_only=True)
class InvoiceLineDTO:
    """One line of an invoice. ``project_id``/``billing_item_id`` are set only for a generated
    (``TIME``/``EXPENSE``) line — ``None`` for a ``MANUAL`` one. ``unit`` is free text (``"hour"``,
    ``"day"`` for a generated time line, ``"pcs"`` for a generated expense line or a manual one),
    not ``projects.contracts.BillingUnit`` — a manual line has no unit of its own to borrow.
    ``amount`` is always ``quantity * unit_price``, quantized to 0.01 (``ROUND_HALF_UP``)."""

    id: UUID
    position: int
    kind: InvoiceLineKind
    description: str
    quantity: Decimal
    unit: str
    unit_price: Decimal
    amount: Decimal
    project_id: UUID | None
    billing_item_id: UUID | None


@dataclass(frozen=True, slots=True, kw_only=True)
class InvoicePeriodDTO:
    """One billing period this invoice was built from (or still covers) — a
    ``timesheets.contracts.BillingPeriodRef`` plus display names, for the invoice detail page."""

    project_id: UUID
    project_name: str
    period_start: date


@dataclass(frozen=True, slots=True, kw_only=True)
class InvoiceDTO:
    id: UUID
    customer: InvoiceCustomerDTO
    status: InvoiceStatus
    # Allocated only when issued (T8) — ``None`` for every draft.
    number: str | None
    invoice_date: date
    due_date: date
    # ISO 4217, taken from the customer at creation.
    currency: str
    # "sv" or "en" — see ``customers.contracts.INVOICE_LOCALES``. Taken from the customer at
    # creation, falling back to the company default; always set (never ``None``) from then on.
    locale: str
    # ``None`` means no VAT line (e.g. reverse charge, explained instead via ``vat_note``).
    vat_rate: Decimal | None
    vat_note: str | None
    your_reference: str | None
    notes: str | None
    subtotal: Decimal
    vat_amount: Decimal
    total: Decimal
    issued_at: datetime | None
    paid_on: date | None
    voided_at: datetime | None
    void_reason: str | None
    lines: tuple[InvoiceLineDTO, ...]
    periods: tuple[InvoicePeriodDTO, ...]
    created_at: datetime
    updated_at: datetime


