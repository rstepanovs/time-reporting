# --- Commands ---


@dataclass(frozen=True, slots=True, kw_only=True)
class CreateInvoiceDraft(Command[InvoiceDTO]):
    """Build a draft invoice for ``customer_id`` from ``periods``, and mark each of them invoiced.

    Every period must be sent, not internal, not already invoiced, and belong to ``customer_id`` —
    checked for all of ``periods`` before anything is written. Raises
    ``InvoiceCustomerNotFoundError``, ``InvoiceNoPeriodsError`` (``periods`` is empty),
    ``InvoicePeriodNotEligibleError`` or ``BillingItemRateMissingError`` (some ``hour``/``day``
    billing item used in scope has no ``unit_rate`` — lists every such item; a missing
    ``markup_percent`` on an ``amount`` item is not an error, it just means no markup is applied).

    ``invoice_date`` is supplied by the router (``date.today()``), like
    ``timesheets.contracts.GetTeamMonthOverview.today`` — never computed inside the service, so
    tests can pin it.
    """

    customer_id: UUID
    periods: tuple[BillingPeriodRef, ...]
    invoice_date: date
    actor_id: UUID


@dataclass(frozen=True, slots=True, kw_only=True)
class InvoiceLineChange:
    """One line's new value. ``line_id=None`` creates a manual line (``InvoiceLineKind.MANUAL``,
    no ``project_id``/``billing_item_id``); given, it updates that line's editable fields without
    changing its ``kind``/``project_id``/``billing_item_id`` — so editing a generated line's
    description or price doesn't turn it into a manual one. ``amount`` is never part of the
    change — the service always recomputes it as ``quantity * unit_price``."""

    line_id: UUID | None
    description: str
    quantity: Decimal
    unit: str
    unit_price: Decimal


@dataclass(frozen=True, slots=True, kw_only=True)
class UpdateInvoiceDraft(Command[InvoiceDTO]):
    """Apply header field changes and a batch of line changes/deletes to ``invoice_id`` in one
    transaction, recomputing ``subtotal``/``vat_amount``/``total`` from the result.

    Every field left ``None`` is not changed; optional fields named in ``clear_fields`` are reset
    to ``None`` instead. Every line change is validated before any is applied, so a rejected batch
    leaves the invoice unchanged. Raises ``InvoiceNotFoundError``, ``InvoiceNotDraftError`` (only a
    draft is editable) or ``InvoiceLineNotFoundError``.
    """

    invoice_id: UUID
    actor_id: UUID
    invoice_date: date | None = None
    due_date: date | None = None
    vat_rate: Decimal | None = None
    vat_note: str | None = None
    your_reference: str | None = None
    notes: str | None = None
    lines: tuple[InvoiceLineChange, ...] = ()
    delete_line_ids: frozenset[UUID] = frozenset()
    clear_fields: frozenset[ClearableInvoiceField] = frozenset()


@dataclass(frozen=True, slots=True, kw_only=True)
class DeleteInvoiceDraft(Command[None]):
    """Delete a draft invoice and free every billing period it covered (a nested
    ``timesheets.ClearBillingPeriodsInvoiced``). Raises ``InvoiceNotFoundError`` or
    ``InvoiceNotDraftError``."""

    invoice_id: UUID
    actor_id: UUID


# --- Exceptions ---


class InvoiceError(Exception):
    """Base class for invoices module domain errors."""


class InvoiceNotFoundError(InvoiceError):
    def __init__(self, invoice_id: UUID) -> None:
        super().__init__(f"Invoice {invoice_id} not found")
        self.invoice_id = invoice_id


class InvoiceCustomerNotFoundError(InvoiceError):
    def __init__(self, customer_id: UUID) -> None:
        super().__init__(f"Customer {customer_id} not found")
        self.customer_id = customer_id


class InvoiceNoPeriodsError(InvoiceError):
    def __init__(self) -> None:
        super().__init__("At least one billing period is required")


class InvoicePeriodNotEligibleError(InvoiceError):
    """Raised by ``CreateInvoiceDraft`` when a referenced period isn't sent, is already invoiced,
    is on an internal project, or doesn't belong to the invoice's customer."""

    def __init__(self, project_id: UUID, period_start: date, reason: str) -> None:
        super().__init__(
            f"Project {project_id}'s period starting {period_start} is not eligible for "
            f"invoicing: {reason}"
        )
        self.project_id = project_id
        self.period_start = period_start
        self.reason = reason


class BillingItemRateMissingError(InvoiceError):
    """Raised by ``CreateInvoiceDraft`` when an ``hour``/``day`` billing item used in the
    invoiced periods has no ``unit_rate`` set — ``items`` names every such item
    (``"<project> — <item>"``)."""

    def __init__(self, items: tuple[str, ...]) -> None:
        super().__init__(f"Missing a unit rate for: {', '.join(items)}")
        self.items = items


class InvoiceNotDraftError(InvoiceError):
    """Raised by ``UpdateInvoiceDraft``/``DeleteInvoiceDraft`` once the invoice has left
    ``DRAFT`` (issued invoices are immutable; see ``InvoiceStatus``)."""

    def __init__(self, invoice_id: UUID, status: InvoiceStatus) -> None:
        super().__init__(f"Invoice {invoice_id} is {status}, not draft")
        self.invoice_id = invoice_id
        self.status = status


class InvoiceLineNotFoundError(InvoiceError):
    def __init__(self, line_id: UUID) -> None:
        super().__init__(f"Invoice line {line_id} not found")
        self.line_id = line_id
